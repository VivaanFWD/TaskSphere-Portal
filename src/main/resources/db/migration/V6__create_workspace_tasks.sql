CREATE TABLE workspace_tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_profile_id UUID NOT NULL REFERENCES academic_profiles(id),
    faculty_profile_id UUID REFERENCES academic_profiles(id),
    title VARCHAR(150) NOT NULL,
    description VARCHAR(1000),
    category VARCHAR(20) NOT NULL,
    priority VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    due_date DATE,
    submission_note VARCHAR(2000),
    submitted_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT ck_workspace_task_category CHECK (category IN ('ASSIGNMENT', 'LAB', 'PROJECT', 'EXAM', 'STUDY')),
    CONSTRAINT ck_workspace_task_priority CHECK (priority IN ('HIGH', 'MEDIUM', 'LOW')),
    CONSTRAINT ck_workspace_task_status CHECK (status IN ('PENDING', 'IN_PROGRESS', 'COMPLETED')),
    CONSTRAINT ck_workspace_task_assignment CHECK (faculty_profile_id IS NULL OR faculty_profile_id <> student_profile_id),
    CONSTRAINT ck_workspace_task_submission CHECK (
        (submitted_at IS NULL AND submission_note IS NULL)
        OR (submitted_at IS NOT NULL AND faculty_profile_id IS NOT NULL AND status = 'COMPLETED')
    )
);

CREATE INDEX ix_workspace_tasks_student_due ON workspace_tasks (student_profile_id, due_date, created_at);
CREATE INDEX ix_workspace_tasks_faculty_due ON workspace_tasks (faculty_profile_id, due_date, created_at);
